import os
import email
import email.policy
import email.utils
import re
from datetime import datetime

CURRENT_DATE = datetime(2026, 11, 26, 12, 40)
SOURCE_DIR = "extracts" if os.path.exists("extracts") and len(os.listdir("extracts")) > 1 else "source"

def scan_mailbox():
    emails = []
    for root, dirs, files in os.walk(SOURCE_DIR):
        for f in files:
            if f.endswith((".zip", ".rar", ".pdf")):
                continue
            path = os.path.join(root, f)
            if os.path.getsize(path) == 0:
                continue
            try:
                with open(path, "rb") as fp:
                    msg = email.message_from_binary_file(fp, policy=email.policy.default)
                subj = str(msg.get("subject", "")).strip()
                sender = str(msg.get("from", "")).strip()
                date_str = str(msg.get("date", "")).strip()
                msg_id = str(msg.get("message-id", "")).strip()
                
                # date parse
                dt = None
                if date_str:
                    try:
                        dt = email.utils.parsedate_to_datetime(date_str)
                    except Exception:
                        pass
                if not dt:
                    for r in msg.get_all("received", []):
                        parts = r.split(";")
                        if len(parts) > 1:
                            try:
                                dt = email.utils.parsedate_to_datetime(parts[-1].strip())
                                break
                            except Exception:
                                pass
                
                body = ""
                if msg.is_multipart():
                    for part in msg.walk():
                        if part.get_content_type() == "text/plain":
                            try:
                                body += part.get_content()
                            except Exception:
                                pass
                else:
                    try:
                        body = msg.get_content()
                    except Exception:
                        pass
                
                emails.append({
                    "subject": subj,
                    "sender": sender,
                    "date": dt,
                    "date_str": dt.strftime("%Y-%m-%d %H:%M") if dt else "UNKNOWN",
                    "msg_id": msg_id,
                    "body": body,
                    "file": f,
                    "path": path
                })
            except Exception:
                pass
    return emails

